#!/usr/bin/env bash
# Create a resource-capped BuildKit builder and make it the default.
# The default builder runs inside dockerd, where `cgroup-parent` does not reach
# build steps. This one runs BuildKit in a container, so every RUN step is
# inside that container's cgroup (and inside dockerdev.slice). No sudo needed.
# `default-load` keeps `docker build` loading images into the local store.
# Limits come from BUILD_* in limits.conf; `dev limits apply` reruns this.
#
#   bash <sandbox>/system/docker/setup-builder.sh
# Undo: docker buildx use default && docker buildx rm capped
#       && rm <sandbox>/state/builder.applied
set -euo pipefail

src=$(dirname "$(readlink -f "$0")")
sb=$(cd "$src/../.." && pwd)
BUILD_MEMORY=4G BUILD_MEMORY_SWAP=6G BUILD_CPU_CORES=2 BUILD_CACHE_GB=10
# shellcheck source=/dev/null
[[ -f $sb/limits.conf ]] && . "$sb/limits.conf"

# The daemon-wide builder.gc setting in daemon.json does not apply to a
# docker-container builder, so its cache limits live in this file.
printf '%s\n' \
  "# Generated by setup-builder.sh from BUILD_CACHE_GB in limits.conf." \
  "[worker.oci]" \
  "  gc = true" \
  "  reservedSpace = \"2GB\"" \
  "  maxUsedSpace = \"${BUILD_CACHE_GB}GB\"" \
  "  minFreeSpace = \"10GB\"" > "$src/buildkitd.toml"

docker buildx inspect capped >/dev/null 2>&1 && docker buildx rm capped

docker buildx create --name capped --driver docker-container \
  --driver-opt default-load=true \
  --driver-opt "memory=$BUILD_MEMORY" --driver-opt "memory-swap=$BUILD_MEMORY_SWAP" \
  --driver-opt cpu-period=100000 --driver-opt "cpu-quota=$((BUILD_CPU_CORES * 100000))" \
  --buildkitd-config "$src/buildkitd.toml" \
  --bootstrap >/dev/null

docker buildx use capped
mkdir -p "$sb/state"
# env.sh sets BUILDX_BUILDER=capped once this exists; plain `docker build`
# ignores `buildx use`.
printf '%s\n' "$BUILD_MEMORY $BUILD_MEMORY_SWAP $BUILD_CPU_CORES $BUILD_CACHE_GB" > "$sb/state/builder.applied"
# With rootless Docker the "default" context still points at the rootful
# socket, and listing its builder fails; that error is noise here.
docker buildx ls 2>/dev/null
